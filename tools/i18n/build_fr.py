    en = open(os.path.join(SITE, 'en.html'), encoding='utf-8').read()
    cut = en.index('<script>')                 # only the markup is translated; the script speaks both languages
    head, script = en[:cut], en[cut:]
    missing = []
    for a, b in sorted(FR, key=lambda p: -len(p[0])):   # longest first, so no line eats a part of a longer one
        if a not in head: missing.append(a); continue
        head = head.replace(a, b)
    if missing:
        sys.exit('Not found in en.html (changed? update build_fr.py):\n  ' + '\n  '.join(missing))
    open(os.path.join(SITE, 'index.html'), 'w', encoding='utf-8').write(head + script)
    print('index.html (FR) written,', len(FR), 'lines swapped')

